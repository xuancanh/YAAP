/**
 * Builds server/src/registry/builtin-companies.generated.ts from
 * blueprints/first-party/*.company.json — the first-party starter
 * blueprints (docs/blueprints.md §3a, docs/foundry.md §10.2) the Market's
 * Companies tab lists as "Official" beside the published ones.
 *
 *   node scripts/build-builtin-companies.mjs
 *
 * Each file is a COMPANY.json v1 document (format "yaam-company/1"); the
 * strict validation (validateBlueprint) and the envelope and role checks run
 * in tests/backend-builtin-companies.test.ts, so this build only parses,
 * orders and embeds. The order is the starter catalog's (foundry.md §10.2);
 * a file not named there follows, alphabetically.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
// BLUEPRINTS_SRC / BLUEPRINTS_OUT redirect the build (the test builds to a scratch file).
const SRC = process.env.BLUEPRINTS_SRC || join(ROOT, 'blueprints/first-party');
const OUT = process.env.BLUEPRINTS_OUT || join(ROOT, 'server/src/registry/builtin-companies.generated.ts');
const SLUG_RE = /^[a-z0-9][a-z0-9-]{1,63}$/;
const ORDER = ['saas-startup', 'agency', 'e-commerce-shop', 'open-source-project', 'research-lab', 'solo-creator', 'professional-services-firm'];

const files = readdirSync(SRC).filter((f) => f.endsWith('.company.json'));
const items = files.map((f) => {
  const slug = f.slice(0, -'.company.json'.length);
  if (!SLUG_RE.test(slug)) throw new Error(`${f}: the file name must be <slug>.company.json`);
  const manifest = JSON.parse(readFileSync(join(SRC, f), 'utf8'));
  if (manifest.format !== 'yaam-company/1') throw new Error(`${f}: format must be "yaam-company/1"`);
  return { slug, manifest };
});
const rank = (s) => { const i = ORDER.indexOf(s); return i < 0 ? ORDER.length : i; };
items.sort((a, b) => rank(a.slug) - rank(b.slug) || a.slug.localeCompare(b.slug));

const header = `/**
 * AUTO-GENERATED by scripts/build-builtin-companies.mjs from
 * blueprints/first-party/*.company.json — do not edit by hand.
 * Regenerate with: node scripts/build-builtin-companies.mjs
 */

export const BUILTIN_COMPANIES: ReadonlyArray<{ slug: string; manifest: Record<string, unknown> }> = `;

writeFileSync(OUT, header + JSON.stringify(items, null, 1) + ';\n');
console.log(`wrote ${OUT}: ${items.length} blueprints`);
